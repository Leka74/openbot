/**
 * `IdGen` port (architecture §3.5): prefixed, monotonic ULIDs (`bot_01J…`, `cnv_…`, `ent_…`).
 *
 * The live layer uses Effect `Clock` and `Random` only (no Bun / node APIs), so `TestClock` and
 * `Random.withSeed` make ids deterministic in tests. Ids sort by creation time within one process.
 */
import type {
  ApprovalRuleId,
  AttachmentId,
  BotId,
  ConversationId,
  EntryId,
  NodeId,
  NotificationId,
  OwnerProfileId,
  RequestId,
  RoutineId,
  RoutineRunId,
  SectionId,
  TaskId,
  TurnId,
} from "@openbot/contracts"
import { IdPrefix as ContractIdPrefix } from "@openbot/contracts"
import { Clock, Context, Effect, Layer, Random, Semaphore } from "effect"

/** Canonical id prefixes: the contract set (architecture §3.5) plus brain-internal ones. */
export const CoreIdPrefix = {
  ...ContractIdPrefix,
  delivery: "dlv",
  epoch: "epc",
  invocation: "inv",
  pairing: "pair",
} as const
export type CoreIdPrefix = (typeof CoreIdPrefix)[keyof typeof CoreIdPrefix]

export interface IdGenShape {
  /** `<prefix>_<ULID>`. Any prefix is accepted; prefer `CoreIdPrefix` values. */
  readonly next: (prefix: string) => Effect.Effect<string>
  readonly botId: Effect.Effect<BotId>
  readonly conversationId: Effect.Effect<ConversationId>
  readonly entryId: Effect.Effect<EntryId>
  readonly requestId: Effect.Effect<RequestId>
  readonly turnId: Effect.Effect<TurnId>
  readonly routineId: Effect.Effect<RoutineId>
  readonly routineRunId: Effect.Effect<RoutineRunId>
  readonly nodeId: Effect.Effect<NodeId>
  readonly sectionId: Effect.Effect<SectionId>
  readonly attachmentId: Effect.Effect<AttachmentId>
  readonly ruleId: Effect.Effect<ApprovalRuleId>
  readonly notificationId: Effect.Effect<NotificationId>
  readonly taskId: Effect.Effect<TaskId>
  readonly profileId: Effect.Effect<OwnerProfileId>
}

const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

const encodeTime = (ms: number): string => {
  let out = ""
  let t = Math.max(0, Math.floor(ms))
  for (let i = 0; i < 10; i++) {
    out = CROCKFORD[t % 32] + out
    t = Math.floor(t / 32)
  }
  return out
}

/** Builds an `IdGenShape` from a `(prefix) => Effect<string>` source. */
export const makeIdGenShape = (next: (prefix: string) => Effect.Effect<string>): IdGenShape => {
  const typed = <A>(prefix: string) => next(prefix) as Effect.Effect<unknown> as Effect.Effect<A>
  return {
    next,
    botId: typed<BotId>(CoreIdPrefix.bot),
    conversationId: typed<ConversationId>(CoreIdPrefix.conversation),
    entryId: typed<EntryId>(CoreIdPrefix.entry),
    requestId: typed<RequestId>(CoreIdPrefix.request),
    turnId: typed<TurnId>(CoreIdPrefix.turn),
    routineId: typed<RoutineId>(CoreIdPrefix.routine),
    routineRunId: typed<RoutineRunId>(CoreIdPrefix.routineRun),
    nodeId: typed<NodeId>(CoreIdPrefix.node),
    sectionId: typed<SectionId>(CoreIdPrefix.section),
    attachmentId: typed<AttachmentId>(CoreIdPrefix.attachment),
    ruleId: typed<ApprovalRuleId>(CoreIdPrefix.rule),
    notificationId: typed<NotificationId>(CoreIdPrefix.notification),
    taskId: typed<TaskId>(CoreIdPrefix.task),
    profileId: typed<OwnerProfileId>(CoreIdPrefix.profile),
  }
}

/**
 * Monotonic ULID factory. Within the same millisecond the 80-bit random part is incremented, so ids
 * generated by one generator are strictly increasing.
 */
export const makeUlidGenerator = Effect.sync(() => {
  let lastTime = -1
  let lastRandom: Array<number> = []
  const nextUlid: Effect.Effect<string> = Effect.gen(function* () {
    const now = yield* Clock.currentTimeMillis
    if (now <= lastTime && lastRandom.length === 16) {
      // Increment the random part (base 32, big-endian) to stay monotonic.
      let i = 15
      while (i >= 0) {
        const digit = lastRandom[i]! + 1
        if (digit < 32) {
          lastRandom[i] = digit
          break
        }
        lastRandom[i] = 0
        i--
      }
    } else {
      const digits: Array<number> = []
      for (let i = 0; i < 16; i++) digits.push(yield* Random.nextIntBetween(0, 32, { halfOpen: true }))
      lastRandom = digits
      lastTime = now
    }
    return encodeTime(lastTime) + lastRandom.map((d) => CROCKFORD[d]).join("")
  })
  return nextUlid
})

export class IdGen extends Context.Service<IdGen, IdGenShape>()("openbot/core/IdGen") {
  /** Live layer: monotonic ULIDs from `Clock` + `Random`. */
  static readonly layer: Layer.Layer<IdGen> = Layer.effect(
    IdGen,
    Effect.gen(function* () {
      const ulid = yield* makeUlidGenerator
      // Serialize so concurrent fibers never observe the same (time, random) pair.
      const lock = yield* Semaphore.make(1)
      return IdGen.of(makeIdGenShape((prefix) => lock.withPermits(1)(Effect.map(ulid, (u) => `${prefix}_${u}`))))
    }),
  )
}
